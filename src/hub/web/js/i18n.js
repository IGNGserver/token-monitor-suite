export function resolveLocale(preference = 'auto') {
  if (preference && preference !== 'auto' && MESSAGES[preference]) return preference;
  const langs = typeof navigator !== 'undefined' ? (navigator.languages || [navigator.language]) : ['en'];
  for (const lang of langs) {
    const lower = String(lang || '').toLowerCase();
    if (lower.startsWith('zh-tw') || lower.startsWith('zh-hant')) return 'zh-TW';
    if (lower.startsWith('zh')) return 'zh-CN';
    if (lower.startsWith('ja')) return 'ja';
    if (lower.startsWith('ko')) return 'ko';
    if (lower.startsWith('en')) return 'en';
  }
  return 'en';
}

export function t(locale, key, params = {}) {
  const table = MESSAGES[locale] || MESSAGES.en;
  let text = table[key] || MESSAGES.en[key] || key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyI18n(root, locale) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(locale, el.getAttribute('data-i18n'));
  }
}
