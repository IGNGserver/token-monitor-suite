'use strict';
// Deterministic, offline runtime assets from the pinned official distribution.
const fs = require('node:fs');
const path = require('node:path');
const { webLightTheme, webDarkTheme } = require('@fluentui/tokens');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'node_modules/@fluentui/web-components');
const target = path.join(root, 'src/shared-ui/vendor');
fs.mkdirSync(target, { recursive: true });
fs.copyFileSync(path.join(source, 'dist/web-components-all.min.js'), path.join(target, 'fluent.js'));
fs.copyFileSync(path.join(root, 'node_modules/@fluentui/tokens/LICENSE'), path.join(target, 'FLUENT-LICENSE.txt'));
const theme = (selector, values) => `${selector} {\n${Object.entries(values).map(([key, value]) => `  --${key}: ${value};`).join('\n')}\n}`;
fs.writeFileSync(path.join(root, 'src/shared-ui/styles/fluent-tokens.css'), `/* Generated by npm run update:fluent-assets. Official Fluent UI tokens; do not edit. */\n${theme(':root', webLightTheme)}\n${theme('html[data-theme="dark"]', webDarkTheme)}\n`);
